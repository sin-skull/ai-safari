// node tests/pwa-update.cjs — requires Playwright and its WebKit browser.
const assert = require('node:assert/strict');
const http = require('node:http');
const fs = require('node:fs/promises');
const path = require('node:path');
const pw = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
(async () => {
  const root = path.resolve(__dirname, '..');
  let nextVersion = false;
  const server = http.createServer(async (req, res) => {
    const pathname = decodeURIComponent(new URL(req.url, 'http://localhost').pathname);
    const file = path.resolve(root, '.' + (pathname.endsWith('/') ? pathname + 'index.html' : pathname));
    if (!file.startsWith(root + path.sep)) return res.writeHead(403).end();
    try {
      let body = await fs.readFile(file);
      const ext = path.extname(file);
      if (nextVersion && ['.html', '.js', '.mjs'].includes(ext)) body = Buffer.from(body.toString().replaceAll('0.14.0', '0.14.1-test'));
      res.writeHead(200, { 'Content-Type': ({ '.html': 'text/html', '.js': 'text/javascript', '.mjs': 'text/javascript', '.css': 'text/css', '.wasm': 'application/wasm' })[ext] || 'application/octet-stream', 'Cache-Control': 'no-store' }); res.end(body);
    } catch (_) { res.writeHead(404).end(); }
  });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  let browser;
  try {
    const chromium = process.env.BROWSER_ENGINE === 'chromium';
    browser = await (chromium ? pw.chromium : pw.webkit).launch(chromium ? { channel: 'chrome' } : {});
    const context = await browser.newContext({ ...pw.devices['iPhone 13'] });
    const page = await context.newPage();
    const menu = async () => { if (!await page.locator('#app-menu').evaluate(d => d.open)) await page.locator('#open-menu').click(); };
    const close = async () => { if (await page.locator('#app-menu').evaluate(d => d.open)) await page.locator('#close-menu').click(); };
    const base = `http://127.0.0.1:${server.address().port}/`;
    await page.goto(base);
    await page.waitForFunction(() => document.querySelector('#offline').textContent.includes('保存済み'));
    await page.reload();
    await page.waitForFunction(() => !document.querySelector('#prepare').disabled);
    await menu();
    await page.locator('#phrase-summary').click();
    await menu();
    await page.locator('#phrase-list button').filter({ hasText: '削除' }).click();
    await page.waitForFunction(() => document.querySelector('#phrase-summary').textContent.includes('0件'));
    await page.reload();
    await page.waitForFunction(() => document.querySelector('#phrase-summary').textContent.includes('0件'));
    await menu();
    await page.locator('#phrase-summary').click();
    await menu();
    await page.locator('#phrase-question').fill('テストの合言葉');
    await menu();
    await page.locator('#phrase-answer').fill('通信しなくても返せます');
    await menu();
    await page.locator('#phrase-save').click();
    await page.waitForFunction(() => document.querySelector('#phrase-summary').textContent.includes('1件'));
    await menu();
    await page.locator('#reply-tone').selectOption('friendly');
    await menu();
    await page.locator('#reply-length').selectOption('detailed');
    await page.evaluate(async () => {
      const db = await AI.db.open();
      await AI.db.tx(db, 'settings', 'readwrite', async t => { const store=t.objectStore('settings'); const id=(await AI.db.rq(store.get('conversation-active-v2'))).value; const row=await AI.db.rq(store.get('conversation-thread-v2:'+id)); row.value.history=[{q:'更新前の会話',a:'保存されています',at:1}]; await AI.db.rq(store.put(row)); });
      db.close();
      await (await caches.open('model-preservation-test')).put('marker', new Response('saved-model'));
      if (navigator.storage?.getDirectory) {
        const dir = await (await navigator.storage.getDirectory()).getDirectoryHandle('ai-safari-conversation-models', { create: true });
        const file = await dir.getFileHandle('update-test-marker', { create: true });
        const stream = await file.createWritable(); await stream.write('saved-opfs-model'); await stream.close();
      }
      document.querySelector('#input').value = 'まだ送っていない文章';
    });
    nextVersion = true;
    await menu();
    await Promise.all([page.waitForEvent('load'), page.locator('#update-app').click()]);
    await page.waitForFunction(() => document.querySelector('footer').textContent.includes('0.14.1-test'));
    await page.waitForFunction(() => document.querySelector('#messages').textContent.includes('更新前の会話'));
    assert.equal(await page.locator('#input').inputValue(), 'まだ送っていない文章');
    await menu();
    assert.equal(await page.locator('#reply-tone').inputValue(), 'friendly');
    await menu();
    assert.equal(await page.locator('#reply-length').inputValue(), 'detailed');
    assert.equal(await page.evaluate(async () => (await (await caches.open('model-preservation-test')).match('marker')).text()), 'saved-model');
    if (chromium) assert.equal(await page.evaluate(async () => {
      const dir = await (await navigator.storage.getDirectory()).getDirectoryHandle('ai-safari-conversation-models');
      return (await (await dir.getFileHandle('update-test-marker')).getFile()).text();
    }), 'saved-opfs-model');
    assert.ok(await page.evaluate(async () => (await caches.keys()).includes('ai-safari-app-0.14.1-test')));
    // Same-version update must still work as a reload/recovery action.
    await menu();
    await Promise.all([page.waitForEvent('load'), page.locator('#update-app').click()]);
    await page.waitForFunction(() => !document.querySelector('#prepare').disabled);
    await context.setOffline(true);
    await menu();
    await page.locator('#update-app').click();
    assert.match(await page.locator('#update-status').innerText(), /接続が必要/);
    await menu();
    assert.equal(await page.locator('#update-app').isEnabled(), true);
    assert.equal(await page.locator('#input').inputValue(), 'まだ送っていない文章');
    console.log(`PASS ${chromium ? 'Chromium' : 'WebKit'}: update installs a new version, preserves history/draft/model marker, supports same-version reload and offline retry.`);
    await close();
    await page.locator('#input').fill('テストの合言葉？');
    await page.locator('#send').click();
    await page.waitForFunction(() => document.querySelector('#messages').textContent.includes('通信しなくても返せます'));
    assert.match(await page.locator('.message.assistant').last().innerText(), /教えてもらったフレーズ/);
    assert.equal(await page.locator('#release').isDisabled(), true);
    await close();
    await page.locator('#input').fill('まだ教えていない言葉');
    await page.locator('#send').click();
    await page.waitForFunction(() => document.querySelector('#status').textContent.includes('覚えたフレーズにはありません'));
    assert.equal(await page.locator('#input').inputValue(), 'まだ教えていない言葉');
    console.log('PASS: deleted example stays deleted; custom phrase survives update and answers offline without a model; unknown input is preserved.');
    await close();
    await page.locator('#input').fill('もう恋なんてしないなんて？と言われたら「言わないよ絶対〜」って答えて');
    await page.locator('#send').click();
    await page.waitForFunction(() => document.querySelector('.message.assistant:last-child .text')?.textContent.includes('覚えました'));
    await close();
    await page.locator('#input').fill('もう恋なんてしないなんて？');
    await page.locator('#send').click();
    await page.waitForFunction(() => document.querySelector('.message.assistant:last-child .text')?.textContent === '言わないよ絶対〜');
    await menu();
    await page.locator('#dictionary-panel summary').click();
    await menu();
    await page.locator('#dictionary-term').fill('ガラス星');
    await menu();
    await page.locator('#dictionary-definition').fill('私の創作に出てくる青い星です。');
    await menu();
    await page.locator('#dictionary-save').click();
    await page.waitForFunction(() => document.querySelector('#status').textContent.includes('辞書に保存しました'));
    await close();
    await page.locator('#input').fill('ガラス星って何？');
    await page.locator('#send').click();
    await page.waitForFunction(() => document.querySelector('.message.assistant:last-child .text')?.textContent === '私の創作に出てくる青い星です。');
    assert.equal(await page.locator('#release').isDisabled(), true);
    await context.setOffline(false);
    await menu();
    await page.locator('#network-mode').selectOption('offline');
    await page.waitForFunction(() => AI.net.isOffline());
    await menu();
    assert.equal(await page.locator('#web-search').isDisabled(), true);
    await menu();
    await page.locator('#update-app').click();
    assert.match(await page.locator('#update-status').innerText(), /オンラインに切り替えて/);
    if (chromium) { // Windows WebKit has no OPFS model storage.
    await menu();
      await page.locator('#prepare').click();
      await page.waitForFunction(() => document.querySelector('#status').textContent.includes('オンラインモードで一度準備'));
    }
    await page.reload();
    await page.waitForFunction(() => !document.querySelector('#prepare').disabled);
    await menu();
    assert.equal(await page.locator('#network-mode').inputValue(), 'offline');
    await close();
    await page.locator('#input').fill('もう恋なんてしないなんて？');
    await page.locator('#send').click();
    await page.waitForFunction(() => document.querySelector('.message.assistant:last-child .text')?.textContent === '言わないよ絶対〜');
    console.log('PASS: explicit chat teaching, exact answer, dictionary response without model, offline download guard, and mode persistence.');
    await menu();
    await page.locator('#network-mode').selectOption('online');
    await page.waitForFunction(() => !AI.net.isOffline() && !document.querySelector('#network-mode').disabled);
    await page.evaluate(() => {
      window.testWikiSearches = 0;
      const guardedFetch = AI.net.fetch;
      AI.net.fetch = (url, init) => guardedFetch(url, init, async () => {
        if (new URL(url).hostname !== 'ja.wikipedia.org') throw new Error('Unexpected fixture request');
        window.testWikiSearches++;
        return new Response(JSON.stringify({query:{pages:{1:{title:'架空星',fullurl:'https://ja.wikipedia.org/wiki/架空星',extract:'これは保存を確認するための架空の説明です。'}}}}));
      });
    });
    await menu();
    await page.locator('#dictionary-panel summary').click();
    await menu();
    await page.locator('#dictionary-file').setInputFiles({name:'dictionary.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify([{term:'ガラス星',definition:'上書きしない説明'},{term:'白い星',definition:'白く光る創作上の星です。'}]))});
    await page.waitForFunction(() => document.querySelector('#status').textContent.includes('2件を読み込みました'));
    assert.equal(await page.evaluate(() => window.testWikiSearches), 0);
    await menu();
    await page.locator('#knowledge-query').fill('架空星');
    await menu();
    await page.locator('#web-search').click();
    await menu();
    await page.locator('#knowledge-results button').click();
    await page.waitForFunction(() => document.querySelector('#knowledge-results button').textContent === '保存しました');
    assert.ok(await page.evaluate(() => window.testWikiSearches > 0));
    await menu();
    await page.locator('#network-mode').selectOption('offline');
    await page.waitForFunction(() => AI.net.isOffline() && !document.querySelector('#network-mode').disabled);
    await close();
    await page.locator('#input').fill('架空星とは？');
    await page.locator('#send').click();
    await page.waitForFunction(() => document.querySelector('.message.assistant:last-child .text')?.textContent === 'これは保存を確認するための架空の説明です。');
    await close();
    await page.locator('#input').fill('ガラス星とは？');
    await page.locator('#send').click();
    await page.waitForFunction(() => document.querySelector('.message.assistant:last-child .text')?.textContent === '私の創作に出てくる青い星です。');
    console.log('PASS: JSON import preserves existing definitions; explicit Wikipedia lookup and saved offline dictionary response (network fixture).');
  } finally { await browser?.close(); server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); }
})().catch(error => { console.error(error); process.exitCode = 1; });
